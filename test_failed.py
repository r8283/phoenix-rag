import rag

QS = [
    "האם ביטוח דירה מכסה נזקי מים?",
    "אילו הרחבות אפשר להוסיף לביטוח תכולת דירה?",
    "האם הביטוח מכסה פריצה לדירה?",
    "איך מתכוננים לחורף כדי למנוע נזקי רטיבות בבית?",
    "איך מגישים תביעה בביטוח רכב?",
]
for q in QS:
    r = rag.answer(q, [])
    print("\n", q, "|", r["status"])
    print(r["answer"])
    for s in r["sources"]:
        print("   ", s)